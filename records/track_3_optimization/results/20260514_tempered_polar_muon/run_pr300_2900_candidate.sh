#!/usr/bin/env bash
set -euo pipefail

SEED="${SEED:-0}"
TRAIN_STEPS="${TRAIN_STEPS:-2900}"
SCHEDULE_STEPS="${SCHEDULE_STEPS:-3020}"
NPROC_PER_NODE="${NPROC_PER_NODE:-1}"
MASTER_ADDR="${MASTER_ADDR:-127.0.0.1}"
MASTER_PORT="${MASTER_PORT:-29501}"
LOCAL_ADDR="${LOCAL_ADDR:-127.0.0.1}"
LOG_DIR="${LOG_DIR:-logs/track3_submission}"
SCRIPT="records/track_3_optimization/results/20260514_tempered_polar_muon/train_gpt_pr300_tempered_polar_2900.py"

mkdir -p "$LOG_DIR"

TRAIN_STEPS="$TRAIN_STEPS" \
SCHEDULE_STEPS="$SCHEDULE_STEPS" \
DENSE_EVAL_START="${DENSE_EVAL_START:-2800}" \
DENSE_EVAL_END="${DENSE_EVAL_END:-$TRAIN_STEPS}" \
DENSE_EVAL_STRIDE="${DENSE_EVAL_STRIDE:-10}" \
CONTRA_TO_NORMAL_END_STEP="${CONTRA_TO_NORMAL_END_STEP:-2750}" \
TEMPERED_POLAR_RHO="${TEMPERED_POLAR_RHO:-0.05}" \
TEMPERED_POLAR_MAX_DELTA="${TEMPERED_POLAR_MAX_DELTA:-0.25}" \
TEMPERED_POLAR_RAMP_START_STEP="${TEMPERED_POLAR_RAMP_START_STEP:-0}" \
TEMPERED_POLAR_RAMP_END_STEP="${TEMPERED_POLAR_RAMP_END_STEP:-0}" \
TEMPERED_POLAR_SKIP_MLP_PROJ="${TEMPERED_POLAR_SKIP_MLP_PROJ:-0}" \
AURORA_RELAX_LAMBDA="${AURORA_RELAX_LAMBDA:-0.0}" \
AURORA_RELAX_MAX_DELTA="${AURORA_RELAX_MAX_DELTA:-0.25}" \
AURORA_BETA="${AURORA_BETA:-0.25}" \
AURORA_BETA_LATE="${AURORA_BETA_LATE:-${AURORA_BETA}}" \
AURORA_BETA_DECAY_START_STEP="${AURORA_BETA_DECAY_START_STEP:-0}" \
AURORA_BETA_DECAY_END_STEP="${AURORA_BETA_DECAY_END_STEP:-0}" \
RADIAL_OUTWARD_SCALE="${RADIAL_OUTWARD_SCALE:-0.5}" \
RADIAL_INWARD_SCALE="${RADIAL_INWARD_SCALE:-1.0}" \
RADIAL_OUTWARD_SCALE_LATE="${RADIAL_OUTWARD_SCALE_LATE:-${RADIAL_OUTWARD_SCALE}}" \
RADIAL_DECAY_START_STEP="${RADIAL_DECAY_START_STEP:-0}" \
RADIAL_DECAY_END_STEP="${RADIAL_DECAY_END_STEP:-0}" \
torchrun \
  --nnodes=1 \
  --nproc_per_node="$NPROC_PER_NODE" \
  --master_addr="$MASTER_ADDR" \
  --master_port="$MASTER_PORT" \
  --local_addr="$LOCAL_ADDR" \
  "$SCRIPT" \
  --seed "$SEED" \
  2>&1 | tee "$LOG_DIR/pr300_tempered_polar_2900_seed${SEED}.log"
